#!/usr/bin/env python3
"""Datowl logo: a chunky pixel owl cut out of an orchid tile, with a coral beak.

Edit OWL ('#' cut-out, '.' tile, 'c' coral), then run
    python3 logo.py && npx tauri icon icon.svg -o src-tauri/icons
to rewrite icon.svg (app icon source) and web/public/logo.svg (toolbar logo).
"""
from pathlib import Path

OWL = """
#.......#
##.....##
#########
#..###..#
#..#c#..#
#########
#.#####.#
#.#####.#
.#######.
..##.##..
""".strip().splitlines()

PAD = 2
ORCHID, CORAL = '#d98af5', '#ff5440'
W, H = len(OWL[0]) + 2 * PAD, len(OWL) + 2 * PAD
assert all(len(row) == len(OWL[0]) for row in OWL)


def cell(x, y):
    """'#' cut-out, '.' tile or 'c' coral at tile coordinates."""
    fx, fy = x - PAD, y - PAD
    if 0 <= fy < len(OWL) and 0 <= fx < len(OWL[0]):
        return OWL[fy][fx]
    return '.'


# One path per colour: separate rects show hairline seams between rows when scaled.
def path(ch, fill):
    d = ''
    for y in range(H):
        x = 0
        while x < W:
            if cell(x, y) == ch:
                start = x
                while x < W and cell(x, y) == ch:
                    x += 1
                d += f'M{start} {y}h{x - start}v1h-{x - start}z'
            else:
                x += 1
    return f'<path fill="{fill}" d="{d}"/>'


def svg(width, height, transform):
    return '\n'.join([
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '  <!-- Datowl: pixel owl cut out of an orchid tile, coral beak. Generated by apps/desktop/logo.py. -->',
        f'  <g transform="{transform}">',
        f'    {path(".", ORCHID)}',
        f'    {path("c", CORAL)}',
        '  </g>',
        '</svg>',
        '',
    ])


here = Path(__file__).parent
(here.parent.parent / 'web/public/logo.svg').write_text(svg(W, H, 'translate(0 0)'))
# macOS icon grid: the tile stands 824px tall, centred on the 1024 canvas.
scale = 824 / H
(here / 'icon.svg').write_text(svg(1024, 1024, f'translate({(1024 - W * scale) / 2:g} 100) scale({scale:g})'))
print(f'{W}x{H}')
